#!/usr/bin/env bun
// Installs the omo-profile-sync agent as a per-user background service.
//   darwin: LaunchAgent   linux: systemd --user service + timer   win32: Scheduled Task
// Default is dry-run mode for the agent; pass --apply to let it write. --uninstall removes the
// service (state, logs and backups under ~/.omo/omo-profile-sync are kept).
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname } from "node:path";
import { parseArgs } from "node:util";

export type Platform = "darwin" | "linux" | "win32";

export interface RenderOpts {
  /** Absolute home dir of the target user. */
  home: string;
  /** Absolute path of the bun executable that runs the bundle. */
  bun: string;
  /** Absolute path of the bundled agent (default `<home>/.omo/bin/omo-profile-sync.js`). */
  bundle?: string;
  /** When false (default), the service passes `--dry-run` to the agent. */
  apply?: boolean;
}

export interface RenderedFile {
  /** Absolute destination path. */
  path: string;
  content: string;
}

/**
 * `process.execPath` can be a versioned path that disappears on upgrade (Homebrew Cellar, WinGet
 * package dir). Prefer the stable symlink/link when one exists; otherwise keep execPath.
 */
export function stableBunPath(
  execPath: string,
  platform: Platform,
  exists: (p: string) => boolean = existsSync,
): string {
  if (execPath.includes("/Cellar/bun/")) {
    return ["/opt/homebrew/bin/bun", "/usr/local/bin/bun"].find((p) => exists(p)) ?? execPath;
  }
  if (platform === "win32" && (execPath.includes("\\WinGet\\Packages\\") || execPath.includes("/WinGet/Packages/"))) {
    const local = process.env.LOCALAPPDATA;
    if (local) {
      const link = `${fwd(local).replace(/\/+$/, "")}/Microsoft/WinGet/Links/bun.exe`;
      if (exists(link)) return link;
    }
  }
  return execPath;
}

export const LABEL = "ai.indo.omo-profile-sync";
export const UNIT = "omo-profile-sync";
export const TASK_NAME = "OmoProfileSync";
export const INTERVAL_SECONDS = 60;

const fwd = (p: string): string => p.replace(/\\/g, "/");
const xml = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const psq = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const vbq = (s: string): string => `""${s}""`;
const sdq = (s: string): string => (/[\s"\\]/.test(s) ? `"${s.replace(/(["\\])/g, "\\$1")}"` : s);

export function layout(platform: Platform, o: RenderOpts) {
  const home = platform === "win32" ? fwd(o.home).replace(/\/+$/, "") : o.home.replace(/\/+$/, "");
  const bun = platform === "win32" ? fwd(o.bun) : o.bun;
  const bundle = platform === "win32" ? fwd(o.bundle ?? `${home}/.omo/bin/omo-profile-sync.js`) : (o.bundle ?? `${home}/.omo/bin/omo-profile-sync.js`);
  const stateDir = `${home}/.omo/omo-profile-sync`;
  const args = o.apply ? [] : ["--dry-run"];
  return { home, bun, bundle, stateDir, args };
}

export function render(platform: Platform, opts: RenderOpts): RenderedFile[] {
  const l = layout(platform, opts);
  const argv = [l.bun, l.bundle, ...l.args];

  if (platform === "darwin") {
    const log = `${l.stateDir}/launchd.log`;
    const content = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array>
${argv.map((a) => `    <string>${xml(a)}</string>`).join("\n")}
  </array>
  <key>StartInterval</key>
  <integer>${INTERVAL_SECONDS}</integer>
  <key>RunAtLoad</key>
  <true/>
  <key>StandardOutPath</key>
  <string>${xml(log)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(log)}</string>
</dict>
</plist>
`;
    return [{ path: `${l.home}/Library/LaunchAgents/${LABEL}.plist`, content }];
  }

  if (platform === "linux") {
    const dir = `${l.home}/.config/systemd/user`;
    const service = `[Unit]
Description=omo model profile sync (one pass)

[Service]
Type=oneshot
ExecStart=${argv.map(sdq).join(" ")}
`;
    const timer = `[Unit]
Description=Run omo model profile sync every ${INTERVAL_SECONDS}s

[Timer]
OnBootSec=30s
OnUnitActiveSec=${INTERVAL_SECONDS}s
Persistent=true
Unit=${UNIT}.service

[Install]
WantedBy=timers.target
`;
    return [
      { path: `${dir}/${UNIT}.service`, content: service },
      { path: `${dir}/${UNIT}.timer`, content: timer },
    ];
  }

  // win32: wscript launches a hidden bun (window style 0); the task runs wscript at logon and every minute.
  const vbsPath = `${l.stateDir}/run-hidden.vbs`;
  const ps1Path = `${l.stateDir}/register-task.ps1`;
  const cmdline = argv.map((a) => vbq(a)).join(" ");
  const vbs = `' Generated by omo-profile-sync installer. Runs the agent without a console window.
Set sh = CreateObject("WScript.Shell")
sh.Run "${cmdline}", 0, False
`;
  const ps1 = `# Generated by omo-profile-sync installer.
$ErrorActionPreference = 'Stop'
$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ${psq(`//B //Nologo "${vbsPath}"`)}
$triggers = @((New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME), (New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Minutes 1) -RepetitionDuration (New-TimeSpan -Days 3650)))
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive
$settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 2) -StartWhenAvailable -Hidden
Register-ScheduledTask -TaskName ${TASK_NAME} -Action $action -Trigger $triggers -Principal $principal -Settings $settings -Force | Out-Null
Write-Output 'registered ${TASK_NAME}'
`;
  return [
    { path: vbsPath, content: vbs },
    { path: ps1Path, content: ps1 },
  ];
}

export function statusCommand(platform: Platform, uid?: number): string {
  if (platform === "darwin") return `launchctl print gui/${uid ?? "$UID"}/${LABEL}`;
  if (platform === "linux") return `systemctl --user list-timers ${UNIT}.timer`;
  return `Get-ScheduledTask ${TASK_NAME}`;
}

function run(cmd: string, args: string[], ignoreFailure = false): void {
  const r = spawnSync(cmd, args, { stdio: "inherit" });
  if (r.status !== 0 && !ignoreFailure) {
    throw new Error(`${cmd} ${args.join(" ")} failed (exit ${r.status ?? r.error?.message})`);
  }
}

function writeFiles(files: RenderedFile[]): void {
  for (const f of files) {
    mkdirSync(dirname(f.path), { recursive: true });
    writeFileSync(f.path, f.content);
  }
}

function psFile(path: string): void {
  run("powershell", ["-NoProfile", "-ExecutionPolicy", "Bypass", "-File", path]);
}

export function install(platform: Platform, o: RenderOpts & { prebuilt?: string }): void {
  const l = layout(platform, o);
  mkdirSync(`${l.stateDir}`, { recursive: true });
  mkdirSync(dirname(l.bundle), { recursive: true });
  if (o.prebuilt) {
    copyFileSync(o.prebuilt, l.bundle);
  } else {
    const src = `${import.meta.dir}/sync.ts`;
    run(l.bun, ["build", src, "--target=bun", "--outfile", l.bundle]);
  }
  const files = render(platform, o);
  writeFiles(files);

  if (platform === "darwin") {
    const uid = process.getuid?.() ?? 0;
    const plist = files[0].path;
    run("plutil", ["-lint", plist]);
    run("launchctl", ["bootout", `gui/${uid}/${LABEL}`], true);
    run("launchctl", ["bootstrap", `gui/${uid}`, plist]);
  } else if (platform === "linux") {
    run("systemctl", ["--user", "daemon-reload"]);
    run("systemctl", ["--user", "enable", "--now", `${UNIT}.timer`]);
  } else {
    psFile(files[1].path);
  }
  console.log(`installed (${o.apply ? "apply" : "dry-run"} mode). status: ${statusCommand(platform, process.getuid?.())}`);
}

export function uninstall(platform: Platform, o: RenderOpts): void {
  const l = layout(platform, o);
  const files = render(platform, o);
  if (platform === "darwin") {
    run("launchctl", ["bootout", `gui/${process.getuid?.() ?? 0}/${LABEL}`], true);
  } else if (platform === "linux") {
    run("systemctl", ["--user", "disable", "--now", `${UNIT}.timer`], true);
  } else {
    const ps1 = `${l.stateDir}/unregister-task.ps1`;
    writeFileSync(ps1, `Unregister-ScheduledTask -TaskName ${TASK_NAME} -Confirm:$false -ErrorAction SilentlyContinue\n`);
    psFile(ps1);
    rmSync(ps1, { force: true });
  }
  for (const f of files) rmSync(f.path, { force: true });
  rmSync(l.bundle, { force: true });
  if (platform === "linux") run("systemctl", ["--user", "daemon-reload"], true);
  console.log(`uninstalled. state, logs and backups kept in ${l.stateDir}`);
}

if (import.meta.main) {
  const { values } = parseArgs({
    args: Bun.argv.slice(2),
    options: {
      apply: { type: "boolean", default: false },
      uninstall: { type: "boolean", default: false },
      bundle: { type: "string" },
      home: { type: "string" },
      bun: { type: "string" },
    },
  });
  const platform = process.platform as Platform;
  if (platform !== "darwin" && platform !== "linux" && platform !== "win32") {
    console.error(`unsupported platform: ${platform}`);
    process.exit(1);
  }
  const opts: RenderOpts = { home: values.home ?? homedir(), bun: values.bun ?? stableBunPath(process.execPath, platform), apply: values.apply };
  if (values.uninstall) {
    uninstall(platform, opts);
  } else {
    if (values.bundle && !existsSync(values.bundle)) {
      console.error(`bundle not found: ${values.bundle}`);
      process.exit(1);
    }
    install(platform, { ...opts, prebuilt: values.bundle });
  }
}
